CREATE TABLE IF NOT EXISTS otp_challenges (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose varchar(30) NOT NULL,
    email varchar(100) NOT NULL,
    account_table varchar(32),
    account_id integer,
    challenge_token_hash char(64) NOT NULL,
    otp_hash varchar(255) NOT NULL,
    expires_at timestamp NOT NULL,
    resend_available_at timestamp NOT NULL,
    resend_count smallint NOT NULL DEFAULT 0,
    resend_locked_until timestamp,
    attempts smallint NOT NULL DEFAULT 0,
    ip_address varchar(45),
    used_at timestamp,
    invalidated_at timestamp,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT otp_challenges_purpose_check CHECK (purpose IN ('registration', 'password_reset'))
);

ALTER TABLE applications ADD COLUMN IF NOT EXISTS registration_password_hash varchar(255);
ALTER TABLE otp_challenges ADD COLUMN IF NOT EXISTS resend_count smallint NOT NULL DEFAULT 0;
ALTER TABLE otp_challenges ADD COLUMN IF NOT EXISTS resend_locked_until timestamp;

CREATE INDEX IF NOT EXISTS idx_otp_lookup ON otp_challenges(purpose, email, invalidated_at, used_at);
CREATE INDEX IF NOT EXISTS idx_otp_expiry ON otp_challenges(expires_at);
CREATE INDEX IF NOT EXISTS idx_otp_account ON otp_challenges(account_table, account_id);
