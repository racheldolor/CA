-- Automated email notification delivery tracking for Supabase PostgreSQL.
CREATE TABLE IF NOT EXISTS notification_logs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_email varchar(255) NOT NULL,
    recipient_user_id integer,
    recipient_table varchar(32),
    notification_type varchar(50) NOT NULL,
    related_id integer,
    subject varchar(255) NOT NULL,
    notification_key varchar(255) NOT NULL UNIQUE,
    status varchar(20) NOT NULL DEFAULT 'pending',
    error_message text,
    sent_at timestamp,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_notification_logs_recipient ON notification_logs(recipient_email);
CREATE INDEX IF NOT EXISTS idx_notification_logs_related ON notification_logs(notification_type, related_id);
CREATE INDEX IF NOT EXISTS idx_notification_logs_status ON notification_logs(status);
